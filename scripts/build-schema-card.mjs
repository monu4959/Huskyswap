// Build the agent's schema card from the comments on the nlq views.
//
//   npm run schema-card
//
// Writes src/lib/agent/schema-card.ts: every nlq view with its description,
// columns and which text-to-SQL roles can read it, plus a hash. The agent's
// prompt and describe_view tool read only this file, so the model sees the
// same schema on every run; rerun this after changing the nlq schema (the
// hash changes, which marks training data built on the old schema).

import { createHash } from "node:crypto";
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import pg from "pg";

process.loadEnvFile(fileURLToPath(new URL("../.env.local", import.meta.url)));
const out = new URL("../src/lib/agent/schema-card.ts", import.meta.url);

const TYPE_NAMES = {
  "timestamp with time zone": "timestamptz",
  "timestamp without time zone": "timestamp",
  "character varying": "text",
  "double precision": "float",
};

const db = new pg.Client({ connectionString: process.env.DATABASE_URL, ssl: { rejectUnauthorized: false } });
await db.connect();
const { rows } = await db.query(`
  select c.relname as name,
         obj_description(c.oid, 'pg_class') as description,
         array_remove(array[
           case when has_table_privilege('nlq_student', c.oid, 'select') then 'nlq_student' end,
           case when has_table_privilege('nlq_admin', c.oid, 'select') then 'nlq_admin' end
         ], null) as roles,
         json_agg(json_build_object(
           'name', a.attname,
           'type', format_type(a.atttypid, a.atttypmod),
           'description', col_description(c.oid, a.attnum)
         ) order by a.attnum) as columns
  from pg_class c
  join pg_namespace n on n.oid = c.relnamespace
  join pg_attribute a on a.attrelid = c.oid and a.attnum > 0 and not a.attisdropped
  where n.nspname = 'nlq' and c.relkind in ('v', 'r', 'm')
  group by c.oid, c.relname
  order by c.relname`);
await db.end();

const views = rows.map((v) => ({
  name: v.name,
  description: v.description ?? "",
  roles: v.roles,
  columns: v.columns.map((c) => ({
    name: c.name,
    type: TYPE_NAMES[c.type] ?? c.type,
    ...(c.description ? { description: c.description } : {}),
  })),
}));
const hash = createHash("sha256").update(JSON.stringify(views)).digest("hex").slice(0, 12);

writeFileSync(
  out,
  `// GENERATED by scripts/build-schema-card.mjs from the comments in the nlq schema. Do not edit;
// change the comments in supabase/migrations and run \`npm run schema-card\`.

import type { ViewCard } from "./types.ts";

export const SCHEMA_HASH = "${hash}";

export const SCHEMA_CARD: ViewCard[] = ${JSON.stringify(views, null, 2)};
`,
);
console.log(`${views.length} views, hash ${hash} -> ${fileURLToPath(out)}`);
for (const v of views) console.log(`  ${v.name.padEnd(14)} ${String(v.columns.length).padStart(2)} columns  ${v.roles.join(", ")}`);
